"""Tests for the lash-line correction model patch geometry (face_makeup.core.eyeliner_patch)."""
from __future__ import annotations

import math
from pathlib import Path

import cv2
import numpy as np
import pytest

from face_makeup.core.eyeliner_patch import (
    compute_eye_scale,
    extract_patch,
    reconstruct_point,
    rescale_pq_by_eye_scale,
)


def _marker_image(size: int, marker: tuple[int, int]) -> np.ndarray:
    image = np.zeros((size, size, 3), dtype=np.uint8)
    x, y = marker
    image[y, x] = 255
    return image


class TestExtractPatch:
    def test_shape_dtype_and_range(self):
        rng = np.random.RandomState(0)
        image = rng.randint(0, 256, (100, 100, 3), dtype=np.uint8)
        patch = extract_patch(image, 40.0, 50.0, 60.0, 50.0, (64, 64), -2.0, 3.0, 2.0)
        assert patch.shape == (64, 64, 3)
        assert patch.dtype == np.float32
        assert 0.0 <= patch.min() and patch.max() <= 1.0

    def test_degenerate_pq_returns_uniform_half(self):
        image = np.zeros((50, 50, 3), dtype=np.uint8)
        patch = extract_patch(image, 10.0, 10.0, 10.0, 10.0, (64, 64), -2.0, 3.0, 2.0)
        assert np.all(patch == np.float32(0.5))

    @pytest.mark.parametrize("t", [0.0, 1.0])
    def test_t_maps_to_documented_column_on_centre_row(self, t):
        """R(t) lands at x = (t_max - t) / (t_max - t_min) * (w - 1), y = h // 2."""
        t_min, t_max, size = -2.0, 3.0, 64
        # Horizontal P->Q with |PQ| = 20 so each patch pixel is sub-pixel in the image.
        px, py, qx, qy = 30.0, 60.0, 50.0, 60.0
        rx, ry = reconstruct_point(px, py, qx, qy, t)
        image = _marker_image(120, (int(rx), int(ry)))

        patch = extract_patch(image, px, py, qx, qy, (size, size), t_min, t_max, 2.0)

        brightest = np.unravel_index(np.argmax(patch[..., 0]), patch.shape[:2])
        expected_x = (t_max - t) / (t_max - t_min) * (size - 1)
        assert brightest[0] == pytest.approx(size // 2, abs=1)
        assert brightest[1] == pytest.approx(expected_x, abs=1)


class TestRescalePq:
    def test_preserves_midpoint_and_direction(self):
        px, py, qx, qy = 10.0, 20.0, 13.0, 24.0
        npx, npy, nqx, nqy = rescale_pq_by_eye_scale(px, py, qx, qy, 100.0, 0.2)
        assert (npx + nqx) / 2 == pytest.approx((px + qx) / 2)
        assert (npy + nqy) / 2 == pytest.approx((py + qy) / 2)
        orig = np.array([qx - px, qy - py]) / math.hypot(qx - px, qy - py)
        new = np.array([nqx - npx, nqy - npy])
        np.testing.assert_allclose(new / np.linalg.norm(new), orig)

    def test_length_is_eye_scale_times_factor(self):
        npx, npy, nqx, nqy = rescale_pq_by_eye_scale(0.0, 0.0, 3.0, 4.0, 100.0, 0.2)
        assert math.hypot(nqx - npx, nqy - npy) == pytest.approx(20.0)

    def test_length_floor_is_one_pixel(self):
        npx, npy, nqx, nqy = rescale_pq_by_eye_scale(0.0, 0.0, 3.0, 4.0, 1.0, 0.2)
        assert math.hypot(nqx - npx, nqy - npy) == pytest.approx(1.0)

    def test_degenerate_pq_returned_unchanged(self):
        assert rescale_pq_by_eye_scale(5.0, 5.0, 5.0, 5.0, 100.0, 0.2) == (5.0, 5.0, 5.0, 5.0)


class TestComputeEyeScale:
    def test_bbox_diagonal(self):
        assert compute_eye_scale([(0.0, 0.0), (3.0, 1.0), (1.0, 4.0)]) == pytest.approx(5.0)

    def test_minimum_is_one(self):
        assert compute_eye_scale([(2.0, 2.0), (2.0, 2.0)]) == 1.0

    def test_empty_raises(self):
        with pytest.raises(ValueError):
            compute_eye_scale([])


class TestReconstructPoint:
    @pytest.mark.parametrize(
        ("t", "expected"),
        [(0.0, (10.0, 20.0)), (1.0, (0.0, 0.0)), (0.5, (5.0, 10.0)), (1.2, (-2.0, -4.0))],
    )
    def test_r_equals_t_p_plus_one_minus_t_q(self, t, expected):
        assert reconstruct_point(0.0, 0.0, 10.0, 20.0, t) == pytest.approx(expected)


# ── upstream parity ──────────────────────────────────────────────────────────

_GOLDEN = Path(__file__).parent / "fixtures" / "eyeliner_patch_golden.npz"


@pytest.fixture(scope="module")
def golden():
    data = np.load(_GOLDEN)
    rng = np.random.RandomState(int(data["image_seed"]))
    image = rng.randint(0, 256, tuple(data["image_shape"]), dtype=np.uint8)
    return data, image


class TestUpstreamParity:
    """Patches must equal EyeContourRefiner's patch_utils output exactly.

    The fixture was generated by upstream ``eye_contour/data/patch_utils.py`` on a
    seeded random image with the shipped branch A/B configs. Patches are
    stored as uint8 (``warpAffine`` on uint8 input is integer-valued), so the
    comparison is exact.
    """

    def test_branch_a_and_b_patches_match(self, golden):
        data, image = golden
        for i, (px, py, qx, qy, eye_scale) in enumerate(data["cases"]):
            patch_a = extract_patch(image, px, py, qx, qy, (64, 64), -2.0, 3.0, 2.0)
            pq_b = rescale_pq_by_eye_scale(px, py, qx, qy, eye_scale, 0.2)
            patch_b = extract_patch(image, *pq_b, (64, 64), -0.5, 1.5, 2.0)

            np.testing.assert_allclose(pq_b, data["branch_b_pq"][i], rtol=0, atol=1e-9)
            np.testing.assert_array_equal(np.rint(patch_a * 255).astype(np.uint8), data["patch_a"][i])
            np.testing.assert_array_equal(np.rint(patch_b * 255).astype(np.uint8), data["patch_b"][i])

    def test_eye_scale_matches(self, golden):
        data, _ = golden
        cases = data["cases"]
        points = [(c[0], c[1]) for c in cases] + [(c[2], c[3]) for c in cases]
        assert compute_eye_scale(points) == pytest.approx(float(data["eye_scale_all"]), abs=1e-9)

    def test_opencv_major_below_5(self):
        """OpenCV 5 changes warpAffine rounding, which shifts model input patches."""
        assert int(cv2.__version__.split(".")[0]) < 5
